/**
 * 대화체 채팅 메시지 → 검색 키워드 쿼리 정제 (의존성 없는 순수 함수).
 *
 * 자동 웹검색은 사용자 메시지 전체를 그대로 검색 쿼리로 쓰는데, "지금 대한민국 대통령이
 * 누구인지 웹 검색 결과를 바탕으로 한 문장으로 알려줘." 같은 장황한 지시문이 쿼리에 섞이면
 * 뉴스 API(Naver/News)가 0건을 반환하고 일반 백과 페이지만 남아 시의성 있는 사실(현직 인물 등)을
 * 놓친다. 알려진 지시 문구만 보수적으로 제거해 핵심 키워드를 남긴다. (MCP 도구/fact-check 의
 * 명시적 쿼리는 정제하지 않음 — 이 정제는 **사용자 발화를 그대로 쿼리로 쓰는 경로**,
 * 즉 chat 자동검색과 딥리서치 폴백 서브토픽에만 적용한다.)
 *
 * @module mcp/web-search/query-cleaner
 */
import { stripSlashEnvelope } from '../../chat/slash-command';

/** 제거 대상 대화체 지시 문구 패턴 (한국어 중심). 보수적으로만 — 핵심 명사는 보존. */
const INSTRUCTION_NOISE: readonly RegExp[] = [
    // 검색 지시 표현은 활용 어미까지 통째로 — 아래 `검색` 패턴이 낱말만 지워 "웹에서 … 해서" 가 검색어에
    // 남았다(2026-10-12: "…버전을 웹에서 검색해서 알려줘" → "…버전을 웹에서 해서"). "웹에서"·"인터넷에서" 는
    // 검색 동사가 바로 붙을 때만 지운다 — "웹에서 동작하는 …" 같은 용법은 보존.
    /(웹|인터넷|온라인)\s*상?\s*(에서|으로|에)?\s*(검색\s*(해\s*(서|보고|봐서|봐|줘|주세요|줄래|주실래요)?|하여|하고|한\s*(뒤|다음|후)에?)|찾아\s*(서|보고|봐서|봐|줘|주세요|줄래|주실래요)?)(?![가-힣])/g,
    /검색\s*(해\s*(서|보고|봐서|봐|줘|주세요|줄래|주실래요)?|하여|하고|한\s*(뒤|다음|후)에?)(?![가-힣])/g,
    /찾아\s*(서|보고|봐서)(?![가-힣])/g,
    // 시점 한정 표현은 "기준(으로)" 까지 구 전체 — "오늘 날씨"·"현재 대통령" 처럼 "기준" 없이 쓴 시점 낱말과
    // "기준금리"·"기준 금리" 같은 명사는 보존한다.
    /(오늘|현재|지금)\s*(날짜|시점|일자)?\s*기준(으로는|으로)?(?![가-힣])(?!\s*금리)/g,
    /웹\s*검색(\s*결과)?(을|를|은|는)?\s*(바탕으로|참고(해서|하여)?|통해|이용(해서|하여)?)?/g,
    /검색(\s*결과)?(을|를)?\s*(바탕으로|참고(해서|하여)?)?/g,
    /(한|두|세|짧은)?\s*문장으로/g,
    /(간단히|자세히|상세히|짧게|요약해서|정리해서)/g,
    // 지시 동사 + 종결어미 조합만 잡는다 — "실태 조사 결과" 같은 명사 용법은 보존해야 하므로
    // `조사`/`리서치` 단독은 넣지 않는다(2026-09-13: 딥리서치 폴백 쿼리에 "…조사해줘" 가
    // 그대로 남아 무관한 검색 결과가 보고서 참고문헌에 실렸다).
    /(알려|말해|설명해|답해|정리해|가르쳐|조사해|리서치해|찾아)\s*(줘|주세요|줄래|주실래요|봐)?/g,
    /(이|가|은|는)?\s*누구(야|인지|니|예요|입니까|인가요|신가요)?\s*\??/g,
    /(이|가|은|는)?\s*뭐(야|예요|니)?\s*\??/g,
    /무엇(인지|입니까|인가요)?\s*\??/g,
];

/**
 * 대화체 메시지에서 지시 문구를 제거해 검색 키워드만 남긴다.
 * 과잉 제거로 빈 문자열이 되면 원문을 그대로 반환(안전망).
 */
export function cleanSearchQuery(raw: string): string {
    // 슬래시 스킬 확장 봉투를 먼저 벗긴다 — 호출부가 원문을 넘기는 것이 1차 방어선이지만,
    // 새더라도 스킬 프롬프트 수천 자가 검색어가 되지 않도록 여기서 한 번 더 막는다.
    const original = stripSlashEnvelope((raw || '').trim());
    let q = original;
    for (const re of INSTRUCTION_NOISE) q = q.replace(re, ' ');
    q = q
        .replace(/\s+/g, ' ')
        .replace(/^[\s.?!,]+/g, '')
        .replace(/[\s.?!,]+$/g, '')
        .trim();
    return q.length >= 2 ? q : original;
}
